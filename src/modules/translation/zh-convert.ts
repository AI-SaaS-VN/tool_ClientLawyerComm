const TRADITIONAL_TO_SIMPLIFIED: Record<string, string> = Object.fromEntries(
  Object.entries(SIMPLIFIED_TO_TRADITIONAL).map(([s, t]) => [t, s]),
);

export function convertZh(text: string, targetLang: "zh-Hans" | "zh-Hant"): string {
  const map = targetLang === "zh-Hant" ? SIMPLIFIED_TO_TRADITIONAL : TRADITIONAL_TO_SIMPLIFIED;
  return [...text].map((char) => map[char] ?? char).join("");
}
