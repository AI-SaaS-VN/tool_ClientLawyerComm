function table(lang: string) {
  return isSupportedLang(lang) ? COPY[lang] : COPY.en;
}

export function uiText(lang: string, key: CopyKey): string {
  return table(lang)[key];
}

export function statusText(lang: string, status: string): string {
  const labels = isSupportedLang(lang) ? STATUS[lang] : STATUS.en;
  return labels[status] ?? status;
}

export function machineTag(lang: string, version: number | null): string {
  const mark =
    lang === "zh-Hant" ? "機譯" : lang === "zh-Hans" ? "机译" : lang === "vi" ? "máy dịch" : "MT";
  return `(${mark} v${version ?? 1})`;
}

export function roleText(lang: string, role: string): string {
  if (role === "client") return uiText(lang, "roleClient");
  if (role === "lawyer") return uiText(lang, "roleLawyer");
  if (role === "coordinator") return uiText(lang, "roleCoordinator");
  return role;
}

export function caseStatusText(lang: string, status: string): string {
  if (status === "active") return uiText(lang, "caseActive");
  if (status === "archived") return uiText(lang, "caseArchived");
  return status;
}

